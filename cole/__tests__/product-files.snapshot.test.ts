// ─────────────────────────────────────────────────────────────────────────────
// COLE snapshot suite — SURFACE: product files (the 8 delivered documents).
//
// THIS IS THE PAID DELIVERABLE. It is also the surface that rendered
// "🔴 TIME-SENSITIVE: 31 October 2026" at the top of all eight SUPERLEAVE
// documents for months: the date was removed from the success copy (34dfb30,
// edd9233) and from the gate page (a152989) by hand, but none of those commits
// touched app/files/, so it survived in the one surface a customer pays for.
// Nothing would have caught that. This locks it.
//
// One test file per surface, looping every product × every file. Snapshots at
//   cole/__tests__/__snapshots__/<product-id>.product-files-<num>.snap
//
//   RUN:     npm run test:snap
//   UPDATE:  npm run test:snap:update
//   SCOPED:  npm run test:snap -- --test-name-pattern product-files
//
// No tripwire here: generate-product-files is not gated (only buildSuccessPage
// is), so unlike the success-pages test this file sets no env var.
// ─────────────────────────────────────────────────────────────────────────────
import { test } from "node:test";
import * as path from "node:path";
import { req, COLE_ROOT, loadConfigs, snapshotPath, verbatim } from "./_surfaces.ts";

const { generateAllProductFiles } =
  req(path.join(COLE_ROOT, "generators", "generate-product-files.ts"));

const configs = loadConfigs();

test("the product corpus loaded", (t) => {
  t.assert.ok(configs.length >= 40, `expected ~48 configs, loaded ${configs.length}`);
});

for (const { id, config } of configs) {
  // Generate all 8 once per product rather than once per test: generateProductFile
  // is pure, and 384 separate config loads would dominate the runtime.
  const emitted = generateAllProductFiles(config) as { path: string; content: string }[];

  test(`${id} · product-files · emits one artefact per declared file`, (t) => {
    t.assert.strictEqual(
      emitted.length,
      config.files.length,
      `config declares ${config.files.length} files but the generator emitted ${emitted.length}`,
    );
  });

  config.files.forEach((file: any, i: number) => {
    test(`${id} · product-files-${file.num}`, (t) => {
      const doc = emitted[i];

      // The generator returns a parallel array; assert the pairing rather than
      // trusting index alignment, or a reordering would silently snapshot
      // document 03's content into 02's file.
      t.assert.match(doc.path, new RegExp(`/${file.slug}/page\\.tsx$`),
        `emitted path ${doc.path} does not correspond to declared file ${file.slug}`);

      // Guard the guard: an empty or truncated document would otherwise be
      // accepted by the first --test-update-snapshots run and pass forever.
      t.assert.ok(doc.content.length > 2_000, `document suspiciously short: ${doc.content.length} bytes`);
      t.assert.match(doc.content, /AUTO-GENERATED BY COLE/, "missing the generated-file marker");

      return t.assert.fileSnapshot(doc.content, snapshotPath(id, `product-files-${file.num}`), {
        serializers: verbatim,
      });
    });
  });
}
