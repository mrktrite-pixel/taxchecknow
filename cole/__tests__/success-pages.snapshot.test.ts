// ─────────────────────────────────────────────────────────────────────────────
// COLE snapshot suite — SURFACE: success pages (tier 1 "assess" + tier 2 "plan").
//
// One test file per surface, looping every product. Snapshots land at
//   cole/__tests__/__snapshots__/<product-id>.success-assess.snap
//   cole/__tests__/__snapshots__/<product-id>.success-plan.snap
//
//   RUN:     npm run test:snap
//   UPDATE:  npm run test:snap:update
//
// THERE IS NO LONGER A TRIPWIRE TO BYPASS (F127, 2026-10-14).
//
// This file used to set COLE_SUCCESS_TEMPLATE_RA2_RA3=1 before importing the generator, because
// buildSuccessPage() threw unless that variable was set. The guard now reads the generator's own
// source for the two emit sites it names (buildComposerInputsFromSession and the render-time
// annualDate helper), so there is nothing an environment variable can unlock or hide — and this
// suite no longer needs operator environment setup to run.
//
// The line is REMOVED rather than left as a no-op: a bypass that bypasses nothing still tells the
// next reader that a bypass is needed here, which is how a stale workaround outlives its cause.
// See cole/__tests__/success-guard.test.ts for the guard's own positive and negative controls.
// ─────────────────────────────────────────────────────────────────────────────

import { test } from "node:test";
import * as path from "node:path";
import { req, COLE_ROOT, loadConfigs, snapshotPath, verbatim } from "./_surfaces.ts";

const { generateSuccessAssess, generateSuccessPlan } =
  req(path.join(COLE_ROOT, "generators", "generate-success-pages.ts"));

const configs = loadConfigs();

// Assert the corpus of products is non-empty and plausible BEFORE looping, so a
// resolution failure cannot present itself as "0 tests, all green".
test("the product corpus loaded", (t) => {
  t.assert.ok(configs.length >= 40, `expected ~48 configs, loaded ${configs.length}`);
});

for (const { id, config } of configs) {
  for (const [surface, generate] of [
    ["success-assess", generateSuccessAssess],
    ["success-plan", generateSuccessPlan],
  ] as const) {
    test(`${id} · ${surface}`, (t) => {
      const page = generate(config);

      // Guard the guard. Without these, a silently EMPTY or truncated page would
      // be accepted by the first --test-update-snapshots run and "pass" forever.
      t.assert.ok(page.length > 5_000, `page suspiciously short: ${page.length} bytes`);
      t.assert.match(page, /AUTO-GENERATED BY COLE/, "missing the generated-file marker");
      t.assert.match(page, /get-assessment\?session_id=/, "missing the STEP 1 stored-first fetch");

      return t.assert.fileSnapshot(page, snapshotPath(id, surface), { serializers: verbatim });
    });
  }
}
