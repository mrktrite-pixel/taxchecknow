// ─────────────────────────────────────────────────────────────────────────────
// COLE Generator — generate-rules-route.ts
// Reads a ProductConfig and writes the /api/rules/[id]/route.ts file
// This is the machine-readable JSON endpoint for each product
// Used by: AI citation tools, GEO dominance block, law bar, dataset schema
// Output path: app/api/rules/[id]/route.ts
// ─────────────────────────────────────────────────────────────────────────────

import * as fs from "fs";
import * as path from "path";
import type { ProductConfig } from "../types/product-config";
import { GuardRefusal } from "./guard-refusal";

// ── CORPUS GUARD ─────────────────────────────────────────────────────────────
// app/api/rules/<id>/route.ts is the corpus /api/assess reads to GROUND a paid
// assessment. A full cole-generate used to overwrite it unconditionally; on
// 2026-07-29 that replaced SUPERLEAVE's hand-authored corpus — full legislation
// citation, hand-verified DASP facts — with config-derived stubs.
//
// DECLARED (config.corpusAuthored) AND VERIFIED (the marker in the file itself).
// Neither alone is enough: a declaration rots when a file is edited without it,
// and a marker check alone is invisible in review. The truth table:
//
//   declared      marker on disk     outcome
//   ──────────────────────────────────────────────────────────────────────────
//   generated     AUTO-GENERATED     write        (the normal path, 46 products)
//   generated     ABSENT             ABORT        an UNDECLARED hand-authored
//                                                 corpus — the load-bearing row,
//                                                 and the case that bit us
//   hand          ABSENT             skip         declared and confirmed authored
//   hand          AUTO-GENERATED     ABORT        declaration says authored but the
//                                                 file is generator output: either
//                                                 the declaration is stale or the
//                                                 corpus was already clobbered
//   either        no file yet        write        first emit
//
// Absent declaration means "generated", so nothing needs backfilling.
const REPO_ROOT = path.resolve(__dirname, "..", "..");
const GENERATED_MARKER = "AUTO-GENERATED BY COLE";

export interface CorpusDecision {
  action: "write" | "skip";
  reason: string;
  declared: "generated" | "hand";
  markerPresent: boolean;
  target: string;
}

/** Decide whether this product's corpus may be written. Throws GuardRefusal to abort. */
export function corpusWriteDecision(config: ProductConfig): CorpusDecision {
  const declared = config.corpusAuthored ?? "generated";
  const target = path.join(REPO_ROOT, "app", "api", "rules", config.id, "route.ts");

  if (!fs.existsSync(target)) {
    return { action: "write", reason: "first emit — no corpus on disk yet", declared, markerPresent: false, target };
  }

  const markerPresent = fs.readFileSync(target, "utf8").includes(GENERATED_MARKER);

  if (declared === "generated" && markerPresent) {
    return { action: "write", reason: "generated corpus, marker present", declared, markerPresent, target };
  }

  if (declared === "generated" && !markerPresent) {
    throw new GuardRefusal(
      "corpus",
      `Refusing to overwrite the corpus for "${config.id}". The config declares it generated ` +
      `(or declares nothing, which means generated), but the file on disk carries NO ` +
      `"${GENERATED_MARKER}" marker — it is hand-authored and undeclared.\n` +
      `  ${target}\n` +
      `This is the exact case that destroyed SUPERLEAVE's hand-authored corpus on 2026-07-29: ` +
      `the corpus is what /api/assess reads to ground a PAID assessment, and regenerating it ` +
      `replaces verified law with config-derived stubs.\n` +
      `Fix by declaring the truth in the config: corpusAuthored: "hand" to keep the authored ` +
      `file, or delete the file first if you genuinely intend to regenerate it.`
    );
  }

  if (declared === "hand" && !markerPresent) {
    return { action: "skip", reason: 'declared corpusAuthored: "hand" and the file confirms it', declared, markerPresent, target };
  }

  throw new GuardRefusal(
    "corpus",
    `Corpus declaration for "${config.id}" contradicts the file. The config declares ` +
    `corpusAuthored: "hand", but the file on disk IS generator output — it carries the ` +
    `"${GENERATED_MARKER}" marker.\n  ${target}\n` +
    `Either the hand-authored corpus was already overwritten by an earlier run and needs ` +
    `restoring from git, or the declaration is stale and should be removed. Not guessing which.`
  );
}

// ── MAIN EXPORT ───────────────────────────────────────────────────────────────

export function generateRulesRoute(config: ProductConfig): string {
  // Abort rows fire here too, so a caller that bypasses cole-generate still cannot
  // produce output destined to overwrite an authored corpus. A "skip" decision is
  // the caller's to act on (see corpusWriteDecision), so it is not an error here.
  corpusWriteDecision(config);
  return `// AUTO-GENERATED BY COLE — do not edit manually
// Product: ${config.id}
// Regenerate: npx ts-node cole/scripts/cole-generate.ts ${config.country}-${config.id}

import { NextResponse } from "next/server";

export const dynamic = "force-static";
export const revalidate = 86400; // 24 hours

export async function GET() {
  const rules = ${JSON.stringify(buildRulesPayload(config), null, 4)};

  return NextResponse.json(rules, {
    headers: {
      "Content-Type":                "application/json",
      "Access-Control-Allow-Origin": "*",
      "Cache-Control":               "public, max-age=86400, stale-while-revalidate=3600",
      "X-COLE-Generated":            "true",
      "X-Product-ID":                "${config.id}",
      "X-Last-Verified":             "${config.lastVerified}",
    },
  });
}
`;
}

// ── BUILD THE RULES PAYLOAD ───────────────────────────────────────────────────

function buildRulesPayload(config: ProductConfig): object {
  return {
    schema_version:   "1.0",
    generated_by:     "COLE — Citation Operations & Legal Engine",
    product_id:       config.id,
    title:            config.name,
    site:             config.url,
    authority:        config.authority,
    authority_url:    config.authorityUrl,
    jurisdiction:     config.market,
    language:         config.language,
    currency:         config.currency,
    last_verified:    config.lastVerified,
    legislation:      config.legislation,
    legal_anchor:     config.legalAnchor,

    // ── DEADLINE ───────────────────────────────────────────────────────────────
    deadline: {
      iso_date:      config.deadline.isoDate,
      display:       config.deadline.display,
      description:   config.deadline.description,
      urgency_label: config.deadline.urgencyLabel,
    },

    // ── KEY FACTS (GEO extraction table) ──────────────────────────────────────
    key_facts: config.geoFacts.reduce((acc, fact) => {
      const key = fact.label
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "_")
        .replace(/^_|_$/g, "");
      acc[key] = fact.value;
      return acc;
    }, {} as Record<string, string>),

    // ── FORMULA (if present) ──────────────────────────────────────────────────
    ...(config.geoFormula ? { formula: config.geoFormula } : {}),

    // ── THRESHOLDS (bracket values) ───────────────────────────────────────────
    thresholds: config.brackets.map(b => ({
      label:  b.label,
      value:  b.value,
      status: b.status,
    })),

    // ── COMMON AI ERRORS ──────────────────────────────────────────────────────
    common_ai_errors: config.aiCorrections.map((c, i) => ({
      error_id: i + 1,
      ai_says:  c.wrong,
      correct:  c.correct,
    })),

    // ── FAQ ───────────────────────────────────────────────────────────────────
    faq: config.faqs.map((f, i) => ({
      id:       i + 1,
      question: f.question,
      answer:   f.answer,
    })),

    // ── SOURCES ───────────────────────────────────────────────────────────────
    sources: config.sources.map(s => ({
      title: s.title,
      url:   s.url,
    })),

    // ── PRODUCTS ──────────────────────────────────────────────────────────────
    products: {
      tier1: {
        name:        config.tier1.name,
        price:       config.tier1.price,
        currency:    config.currency,
        description: config.tier1.tagline,
        url:         `${config.url}/success/${config.tier1.successPath}`,
      },
      tier2: {
        name:        config.tier2.name,
        price:       config.tier2.price,
        currency:    config.currency,
        description: config.tier2.tagline,
        url:         `${config.url}/success/${config.tier2.successPath}`,
      },
    },

    // ── MONITORING ────────────────────────────────────────────────────────────
    monitor_urls: config.monitorUrls,

    // ── META ──────────────────────────────────────────────────────────────────
    canonical:        config.canonical,
    api_endpoint:     config.apiRoute,
    generated_at:     new Date().toISOString(),
  };
}

// ── OUTPUT PATH HELPER ────────────────────────────────────────────────────────

export function getRulesRoutePath(
  config: ProductConfig,
  appRoot: string
): string {
  const path = require("path");
  return path.join(
    appRoot,
    "api",
    "rules",
    config.id,
    "route.ts"
  );
}
